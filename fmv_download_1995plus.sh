#!/usr/bin/env bash
# fmv_download_1995plus.sh - download every T.REX ARMS Field Manual Vault PDF dated 1995 or later, plus undated
# 1,901 manuals. Expect roughly 20 to 40 GB.
#
# Usage:   ./fmv_download_1995plus.sh [destination folder] [parallel downloads]
#          defaults: ~/Downloads/FMV_1995plus   4 parallel
# Example: ./fmv_download_1995plus.sh "$HOME/Downloads/Field Manuals" 6
#
# Requires only curl (built into macOS). Safe to re-run: existing files are skipped.
# Files are named "NNNN - DESIGNATION - Title (Year).pdf", numbered newest to oldest.
# Manifest is embedded at the bottom of this file as comment lines: ## num|slug|label

set -u
DEST="${1:-$HOME/Downloads/FMV_1995plus}"
PAR="${2:-4}"
BASE="https://www.trex-arms.com/field-manual-vault/"
mkdir -p "$DEST"
LOG="$DEST/_download_log.txt"
: > "$LOG"
export DEST BASE LOG

worker() {
  IFS='|' read -r num slug label <<< "$1"
  [ -z "$slug" ] && return 0
  safe=$(printf '%s' "$label" | tr '/:*?"<>|' '_' | cut -c1-180)
  out="$DEST/${num} - ${safe}.pdf"
  if [ -s "$out" ]; then echo "SKIP  $num"; echo "SKIP|$num|$slug" >> "$LOG"; return 0; fi
  pdf=$(curl -sSL --max-time 60 "${BASE}${slug}" | grep -o 'https://files\.trex-arms\.com/pdf/[^"]*\.pdf' | head -1)
  if [ -z "$pdf" ]; then echo "FAIL  $num no PDF link at ${BASE}${slug}"; echo "FAIL|$num|$slug|no link" >> "$LOG"; return 0; fi
  echo "GET   $num $label"
  if curl -sSL --fail --retry 3 --max-time 1800 -o "$out" "$pdf"; then
    echo "OK|$num|$slug|$pdf" >> "$LOG"
  else
    rm -f "$out"; echo "FAIL  $num download error $pdf"; echo "FAIL|$num|$slug|$pdf" >> "$LOG"
  fi
}
export -f worker

grep '^## ' "$0" | sed 's/^## //' | tr '\n' '\0' | xargs -0 -n 1 -P "$PAR" bash -c 'worker "$1"' _

ok=$(grep -c '^OK|' "$LOG"); sk=$(grep -c '^SKIP|' "$LOG"); fl=$(grep -c '^FAIL|' "$LOG")
echo
echo "Done. Files in: $DEST"
echo "Downloaded: $ok   Skipped: $sk   Failed: $fl   (details in _download_log.txt)"
echo "Re-run the same command to retry any failures."
exit 0

